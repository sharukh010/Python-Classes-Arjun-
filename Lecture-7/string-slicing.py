# name[start:end:step]
# start,end,step -> this are all optional values 
# if you don't pass start it will consider from 0 
# if you don't pass end it will consider until length i.e, 5 
# if you don't pass step it will consider 1 by default 
# end is exclusive i.e, it will not be included 
# step -> how much you need to add to current index to get the 
# next index 